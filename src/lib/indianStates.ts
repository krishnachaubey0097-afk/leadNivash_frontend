export const DEFAULT_STATE_NAME = 'Haryana';

export function getStateRule(stateName?: string | null): IndianStateRule {
  if (!stateName) {
    return INDIAN_STATES[0];
  }
  const needle = stateName.trim().toLowerCase();
  return (
    INDIAN_STATES.find(
      (s) => s.name.toLowerCase() === needle || s.name.toLowerCase().includes(needle)
    ) || INDIAN_STATES[0]
  );
}
